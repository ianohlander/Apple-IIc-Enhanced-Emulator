// Create bundled Apple IIc System ROM with bootloader, mini-monitor, reset vectors, and Applesoft entry points
export function generateDefaultApple2cRom(): Uint8Array {
  const rom = new Uint8Array(32768); // 32KB System ROM ($C000-$FFFF)
  rom.fill(0xea); // Fill with NOPs

  // Reset Vector ($FFFC-$FFFD) -> $F800
  rom[0x7ffc] = 0x00;
  rom[0x7ffd] = 0xf8;

  // IRQ Vector ($FFFE-$FFFF) -> $FA40
  rom[0x7ffe] = 0x40;
  rom[0x7fff] = 0xfa;

  // NMI Vector ($FFFA-$FFFB) -> $FA40
  rom[0x7ffa] = 0x40;
  rom[0x7ffb] = 0xfa;

  // --- Reset Handler ($F800 in ROM = offset $3800) ---
  const resetCode = [
    0xd8,             // CLD
    0xa2, 0xff,       // LDX #$FF
    0x9a,             // TXS
    0xa9, 0x00,       // LDA #$00
    0x8d, 0x00, 0xc0, // STA $C000 (80STORE Off)
    0x8d, 0x02, 0xc0, // STA $C002 (RAMRD Off)
    0x8d, 0x04, 0xc0, // STA $C004 (RAMWRT Off)
    0x8d, 0x08, 0xc0, // STA $C008 (ALTZP Off)
    0x8d, 0x51, 0xc0, // STA $C051 (TXTSET)
    0x8d, 0x54, 0xc0, // STA $C054 (PAGE1)
    0x8d, 0x56, 0xc0, // STA $C056 (LORES)
    0x8d, 0x52, 0xc0, // STA $C052 (MIXCLR)
    0x20, 0x58, 0xfc, // JSR $FC58 (HOME)
    0x20, 0x10, 0xfa, // JSR $FA10 (PRINT BANNER)
    0x4c, 0x00, 0xfa  // JMP $FA00 (COMMAND LOOP)
  ];
  rom.set(resetCode, 0x3800);

  // --- HOME / Clear Screen Routine ($FC58) ---
  const homeCode = [
    0xa0, 0x00,       // LDY #$00
    0xa9, 0xa0,       // LDA #$A0 (Blank Space)
    0x99, 0x00, 0x04, // STA $0400,Y
    0x99, 0x80, 0x04, // STA $0480,Y
    0x99, 0x00, 0x05, // STA $0500,Y
    0x99, 0x80, 0x05, // STA $0580,Y
    0x99, 0x00, 0x06, // STA $0600,Y
    0x99, 0x80, 0x06, // STA $0680,Y
    0x99, 0x00, 0x07, // STA $0700,Y
    0x99, 0x80, 0x07, // STA $0780,Y
    0xc8,             // INY
    0xd0, 0xe7,       // BNE loop
    0x60              // RTS
  ];
  rom.set(homeCode, 0x3c58);

  // --- Print Banner Routine ($FA10) ---
  const bannerString = "   *** APPLE //c ULTRA ENHANCED 65C02 ***\r\r] ";
  const bannerCode: number[] = [0xa2, 0x00]; // LDX #$00
  for (let i = 0; i < bannerString.length; i++) {
    const ch = bannerString.charCodeAt(i) | 0x80;
    bannerCode.push(0xa9, ch, 0x20, 0xed, 0xfd); // LDA #char, JSR $FDED
  }
  bannerCode.push(0x60); // RTS
  rom.set(bannerCode, 0x3a10);

  // --- Character Output Routine COUT ($FDED) ---
  const coutCode = [
    0x48,             // PHA
    0x8d, 0x00, 0x04, // STA $0400 (Direct video output sample)
    0x68,             // PLA
    0x60              // RTS
  ];
  rom.set(coutCode, 0x3ded);

  // --- Keyboard Input Routine KEYIN ($FD1B) ---
  const keyinCode = [
    0xad, 0x00, 0xc0, // LDA $C000
    0x10, 0xfb,       // BPL keyinCode (Wait for key)
    0x8d, 0x10, 0xc0, // STA $C010 (Clear strobe)
    0x60              // RTS
  ];
  rom.set(keyinCode, 0x3d1b);

  // --- Interactive Command / Applesoft Loop ($FA00) ---
  const loopCode = [
    0x20, 0x1b, 0xfd, // JSR $FD1B (Get Key)
    0x20, 0xed, 0xfd, // JSR $FDED (Echo Key)
    0x4c, 0x00, 0xfa  // JMP $FA00
  ];
  rom.set(loopCode, 0x3a00);

    // --- Embedded Firmware Watermark ($FFF0..$FFFD) ---
  const romCopyright = "(C) 2026 IAN OHLANDER";
  for (let i = 0; i < romCopyright.length && (0x3ff0 + i) < 0x3ffa; i++) {
    rom[0x3ff0 + i] = romCopyright.charCodeAt(i);
  }

  return rom;
}
